import os
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

sns.set_theme(style="whitegrid")
plt.rcParams["figure.figsize"] = (10, 5)

def load_and_inspect_data(filepath):
    print(f"Loading {filepath}...")
    # Fallback encoding to handle potential retail dataset character quirks
    try:
        df = pd.read_csv(filepath, encoding="utf-8")
    except UnicodeDecodeError:
        df = pd.read_csv(filepath, encoding="ISO-8859-1")

    print(f"Initial data shape: {df.shape[0]} rows, {df.shape[1]} cols")
    print("\n--- Null Count per Column ---")
    print(df.isnull().sum())
    return df

def clean_sales_data(df):
    df_clean = df.copy()

    # Normalize column headers to lowercase snake_case
    df_clean.columns = [col.strip().lower().replace(" ", "_") for col in df_clean.columns]

    # Cast invoice dates to datetime
    if "invoicedate" in df_clean.columns:
        df_clean["invoicedate"] = pd.to_datetime(df_clean["invoicedate"], errors="coerce")

    # Clean up description whitespaces & casing
    if "description" in df_clean.columns:
        df_clean["description"] = df_clean["description"].astype(str).str.strip().str.title()

    # Filter out cancellations (Invoice starting with 'C' or negative quantities)
    if "invoiceno" in df_clean.columns and "quantity" in df_clean.columns:
        start_len = len(df_clean)
        is_cancelled = df_clean["invoiceno"].astype(str).str.startswith("C")
        valid_qty = df_clean["quantity"] > 0
        df_clean = df_clean[~is_cancelled & valid_qty]
        print(f"Dropped {start_len - len(df_clean)} cancelled/negative quantity orders.")

    # Clean out zero/negative unit prices (system tests/adjustments)
    if "unitprice" in df_clean.columns:
        df_clean = df_clean[df_clean["unitprice"] > 0]

    # Calculate total line spend
    if "quantity" in df_clean.columns and "unitprice" in df_clean.columns:
        df_clean["total_spend"] = df_clean["quantity"] * df_clean["unitprice"]

    print(f"Cleaned dataset shape: {df_clean.shape}")
    return df_clean

def run_initial_eda(df):
    print("\n--- Summary Stats ---")
    print(df[["quantity", "unitprice", "total_spend"]].describe().round(2))

    # Plot and find top revenue generators
    if "description" in df.columns and "total_spend" in df.columns:
        top_10 = df.groupby("description")["total_spend"].sum().nlargest(10)
        print("\n--- Top 10 Revenue Generating Products ---")
        print(top_10)

        plt.figure(figsize=(10, 5))
        top_10.sort_values().plot(kind="barh", color="#2b5c8f")
        plt.title("Top 10 Products by Total Revenue")
        plt.xlabel("Revenue (USD)")
        plt.ylabel("")
        plt.tight_layout()
        plt.savefig("top_10_products.png")
        print("Saved chart to top_10_products.png")

